function buildSummaryItinerary(trip) {
  const [startDay] = trip.dates.split(" - ");
  return Array.from({ length: trip.days }).map((_, index) => ({
    day: index + 1,
    date: index === 0 ? startDay.replace(/(st|nd|rd|th)/, "") : `Day ${index + 1}`,
    title: index === 0 ? `Arrival for ${trip.shortName}` : index === trip.days - 1 ? "Departure" : `${trip.shortName} Experience Day ${index + 1}`,
    location: trip.route.split(" - ")[Math.min(index, trip.route.split(" - ").length - 1)] || trip.shortName,
    hotel: trip.accommodations[Math.min(index, trip.accommodations.length - 1)]?.hotel || "As per itinerary",
    meals: index === 0 ? "Dinner / As per itinerary" : index === trip.days - 1 ? "Breakfast" : "Breakfast / As per itinerary",
    description:
      index === 0
        ? `Arrive and begin ${trip.title}. The day follows the source itinerary with transfers, check-in and orientation.`
        : index === trip.days - 1
          ? `After breakfast, check out and transfer for departure with memories of ${trip.title}.`
          : `Continue the curated ${trip.title} itinerary covering key route experiences, sightseeing and inclusions listed in the trip document.`,
  }));
}

